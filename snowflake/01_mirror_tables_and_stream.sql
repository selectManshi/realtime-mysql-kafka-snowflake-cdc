  PAYMENT_TYPE STRING,
  PAYMENT_INSTALLMENTS INT,
  PAYMENT_VALUE NUMBER(10,2),
  _SYNCED_AT TIMESTAMP_NTZ,
  _DELETED BOOLEAN DEFAULT FALSE
);

-- ---------- SECTION 2: stream on raw table + one-time reload ----------
-- (the stream only sees rows added AFTER it is created, so we reload once)
CREATE STREAM IF NOT EXISTS ECOM_DB.RAW.CDC_STREAM ON TABLE ECOM_DB.RAW.CDC_EVENTS APPEND_ONLY = TRUE;

TRUNCATE TABLE ECOM_DB.RAW.CDC_EVENTS;

COPY INTO ECOM_DB.RAW.CDC_EVENTS (SRC_TABLE, OP, PAYLOAD, SRC_FILE)
FROM (
  SELECT REGEXP_SUBSTR(METADATA$FILENAME, 'public/([^/]+)/', 1, 1, 'e', 1),
         COALESCE($1:Op::STRING, 'I'),
         $1,
         METADATA$FILENAME
  FROM @ECOM_DB.RAW.S3_RAW
)
PATTERN = '.*public/.*[.]parquet'
FILE_FORMAT = (TYPE = PARQUET)
FORCE = TRUE;

