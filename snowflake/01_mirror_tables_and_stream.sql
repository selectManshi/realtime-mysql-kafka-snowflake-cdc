  SELLER_ZIP_CODE_PREFIX STRING,
  SELLER_CITY STRING,
  SELLER_STATE STRING,
  _SYNCED_AT TIMESTAMP_NTZ,
  _DELETED BOOLEAN DEFAULT FALSE
