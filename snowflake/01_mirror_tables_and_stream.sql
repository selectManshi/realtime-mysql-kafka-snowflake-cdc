-- 01: MIRROR tables (Fivetran-style _SYNCED_AT / _DELETED), stream on the raw table, one-time reload
-- Run each section in its own worksheet using Run All.

-- ---------- SECTION 0: context ----------
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE ECOM_WH;
USE DATABASE ECOM_DB;

-- ---------- SECTION 1: mirror tables ----------
