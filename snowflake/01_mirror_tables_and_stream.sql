CREATE TABLE IF NOT EXISTS ECOM_DB.MIRROR.PRODUCT_CATEGORY_NAME_TRANSLATION (
  PRODUCT_CATEGORY_NAME STRING,
  PRODUCT_CATEGORY_NAME_ENGLISH STRING,
  _SYNCED_AT TIMESTAMP_NTZ,
